    /// <summary>
    ///     Phase stepper shared by both screens: the current stage is gold, stages already passed read as done and
    ///     the ones ahead stay dim, so the two screens look like stages of one flow rather than two unrelated forms.
    /// </summary>
    private void UpdateSteps(SurvivorSetupEuiState state)
    {
        StepDividerOne.Text = Loc.GetString("cmu-survivor-setup-step-divider");
        StepDividerTwo.Text = Loc.GetString("cmu-survivor-setup-step-divider");

        // Role and loadout are one stage: it is active while picking and done once the loadout is confirmed.
        var ready = !_voting && state.MyLoadoutConfirmed;
        var roleDone = _voting || ready;

        ApplyStep(StepRole, "cmu-survivor-setup-step-role", roleDone, !roleDone && !_voting);
        ApplyStep(StepVote, "cmu-survivor-setup-step-vote", _voting && state.MyVote != null, _voting);
        ApplyStep(StepReady, "cmu-survivor-setup-step-ready", false, ready);

        void ApplyStep(Label label, string key, bool done, bool active)
        {
            label.Text = Loc.GetString(key);
            label.Modulate = active ? AccentGold : done ? AccentOpen : Muted;
        }
    }

    /// <summary>The item's own icon, or nothing when the prototype has no sprite worth showing.</summary>
    private void SetLoadoutIcon(TextureRect? icon, string? prototypeId)
    {
        if (icon == null)
            return;

        if (string.IsNullOrEmpty(prototypeId)
            || !_prototypes.TryIndex<EntityPrototype>(prototypeId, out var prototype))
        {
            icon.Texture = null;
            return;
        }

        try
        {
            icon.Texture = _sprite.GetPrototypeIcon(prototype).Default;
        }
        catch (Exception)
        {
            // A prototype without a usable sprite is not worth a broken window.
            icon.Texture = null;
        }
    }

    /// <summary>
    ///     The dedicated survivor job for a role body. The roster carries the body id, not a job: every survivor role
    ///     body's job is named after it ("CMUSurvivorJob" + the body id without its faction prefix), which is the
    ///     mapping the server registers and the survivor job tests pin.
    /// </summary>
    private JobPrototype? JobOfRole(string roleProto)
    {
        if (roleProto.Length == 0)
            return null;

        if (_prototypes.TryIndex(roleProto, out JobPrototype? direct))
            return direct;

        foreach (var prefix in SurvivorJobPrefixes)
        {
            if (!roleProto.StartsWith(prefix, StringComparison.Ordinal))
                continue;

            var candidate = "CMUSurvivorJob" + roleProto[prefix.Length..];
            return _prototypes.TryIndex(candidate, out JobPrototype? job) ? job : null;
        }

        return null;
    }
