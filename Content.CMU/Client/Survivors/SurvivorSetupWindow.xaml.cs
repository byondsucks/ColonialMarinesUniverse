    }

    private Texture? CategoryIcon(SurvivorRoleCategory? category)
    {
        var state = category switch
        {
            SurvivorRoleCategory.Commander or SurvivorRoleCategory.SquadLeader or SurvivorRoleCategory.Leader => "clf_sl",
            SurvivorRoleCategory.Medic => "clf_med",
            SurvivorRoleCategory.Technician => "clf_engi",
            SurvivorRoleCategory.WeaponSpecialist => "clf_spec",
            SurvivorRoleCategory.Liaison => "cmb_obs",
            SurvivorRoleCategory.Support => "cmb_syn",
            _ => "free_rfn",
        };

        if (!_resourceCache.TryGetResource<RSIResource>(RoleIconRsi, out var resource)
            || !resource.RSI.TryGetState(state, out var rsiState))
        {
            return null;
        }

        return rsiState.Frame0;
    }

    /// <summary>
    ///     Rebuilds only the teammate entries whose preview inputs changed. Each row shows the character as
    ///     they will actually appear (profile + the kit of the role/faction they picked), their character
    ///     name, their account name and the role they hold.
    /// </summary>
    /// <summary>
    ///     Armor, helmet and firearm pickers plus the confirm button. Only the winning faction's options are ever
    ///     sent, so the survivor can only choose equipment their faction issues.
    /// </summary>
    private void UpdateLoadout(SurvivorSetupEuiState state)
    {
        // The column stays in place in both states; only its contents change. Hiding it collapsed the body to a
        // single column and left the faction list with a blank strip beside it.
        LoadoutPlaceholder.Visible = !state.HasLoadout;
        LoadoutPanel.Visible = state.HasLoadout;

        if (!state.HasLoadout)
        {
            if (LoadoutSection.Visible)
            {
                LoadoutSection.Visible = false;
                ApplyColumnSplit();
            }

            return;
        }

        if (!LoadoutSection.Visible)
        {
            LoadoutSection.Visible = true;
            ApplyColumnSplit();
        }
        _loadoutConfirmed = state.MyLoadoutConfirmed;

        // The panel is built once per option set and then updated in place. Rebuilding it on every state (which
        // arrives once a second) closed an open dropdown mid-click, so the options could not be chosen at all.
        var signature = string.Join('|', state.ArmorOptions) + "/" + string.Join('|', state.HelmetOptions) + "/" +
                        string.Join('|', state.FirearmOptions);
        if (signature != _loadoutSignature)
        {
            _loadoutSignature = signature;
            LoadoutPanel.RemoveAllChildren();
            _armorSelect = null;
            _helmetSelect = null;
            _firearmSelect = null;

            AddLoadoutSelect("cmu-survivor-setup-armor", SurvivorLoadoutCategory.Armor, state.ArmorOptions,
                state.MyArmor);
            AddLoadoutSelect("cmu-survivor-setup-helmet", SurvivorLoadoutCategory.Helmet, state.HelmetOptions,
                state.MyHelmet);
            AddLoadoutSelect("cmu-survivor-setup-firearm", SurvivorLoadoutCategory.Firearm, state.FirearmOptions,
                state.MyFirearm);

            _confirmLoadout = new Button
            {
                Text = Loc.GetString("cmu-survivor-setup-confirm-loadout"),
                HorizontalExpand = true,
                MinSize = new Vector2(0, 36),
                Margin = new Thickness(0, 6, 0, 0),
                StyleClasses = { "CrtButton" },
            };
            _confirmLoadout.OnPressed += _ => OnConfirmLoadout?.Invoke();
            LoadoutPanel.AddChild(_confirmLoadout);

            _loadoutStatus = new Label { StyleClasses = { "LabelSubText" } };
            LoadoutPanel.AddChild(_loadoutStatus);
        }

        if (_armorSelect is { } armor)
            SyncLoadoutSelect(armor, state.ArmorOptions, state.MyArmor);

        if (_helmetSelect is { } helmet)
            SyncLoadoutSelect(helmet, state.HelmetOptions, state.MyHelmet);

        if (_firearmSelect is { } firearm)
            SyncLoadoutSelect(firearm, state.FirearmOptions, state.MyFirearm);

        SetLoadoutIcon(_armorIcon, state.MyArmor);
        SetLoadoutIcon(_helmetIcon, state.MyHelmet);
        SetLoadoutIcon(_firearmIcon, state.MyFirearm);

        if (_confirmLoadout is { } confirm)
        {
            confirm.Disabled = _loadoutConfirmed;
            confirm.Text = Loc.GetString(_loadoutConfirmed
                ? "cmu-survivor-setup-confirm-loadout-done"
                : "cmu-survivor-setup-confirm-loadout");
            confirm.Modulate = _loadoutConfirmed ? Muted : Color.White;
        }

        if (_loadoutStatus is { } status)
        {
            status.Text = Loc.GetString(_loadoutConfirmed
                ? "cmu-survivor-setup-loadout-confirmed"
                : "cmu-survivor-setup-loadout-unconfirmed");
            status.Modulate = _loadoutConfirmed ? AccentOpen : Muted;
        }

        foreach (var select in new[] { _armorSelect, _helmetSelect, _firearmSelect })
        {
            if (select != null)
                select.Disabled = _loadoutConfirmed;
        }
    }

    private static void SyncLoadoutSelect(OptionButton select, List<string> options, string? current)
    {
        select.Disabled = false;
        for (var i = 0; i < options.Count; i++)
        {
            if (string.Equals(options[i], current, StringComparison.OrdinalIgnoreCase))
            {
                if (select.SelectedId != i)
                    select.Select(i);
                return;
            }
        }
    }

