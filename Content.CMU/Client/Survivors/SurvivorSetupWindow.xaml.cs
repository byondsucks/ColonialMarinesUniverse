    private int FactionRoleCount(string partyId)
    {
        if (!_prototypes.TryIndex<ThirdPartyPrototype>(partyId, out var party)
            || !_prototypes.TryIndex(party.PartySpawn, out PartySpawnPrototype? spawn)
            || spawn == null)
        {
            return 0;
        }

        var count = 0;
        foreach (var amount in spawn.LeadersToSpawn.Values)
            count += amount;
        foreach (var amount in spawn.GruntsToSpawn.Values)
            count += amount;

        return count;
    }

    private Texture? FactionIcon(string partyId)
    {
        if (!_prototypes.TryIndex<ThirdPartyPrototype>(partyId, out var party)
            || party.SurvivorIcons.Count == 0)
        {
            return null;
        }

        var order = new[]
        {
            SurvivorRoleCategory.Leader, SurvivorRoleCategory.SquadLeader, SurvivorRoleCategory.Commander,
            SurvivorRoleCategory.WeaponSpecialist, SurvivorRoleCategory.Medic, SurvivorRoleCategory.Rifleman,
        };

        foreach (var category in order)
        {
            if (party.SurvivorIcons.TryGetValue(category, out var specifier))
                return _sprite.Frame0(specifier);
        }

        return null;
    }

    private void UpdateRoles(SurvivorSetupEuiState state)
    {
        if (_voting)
            return;

        if (_roleRows.Count != state.Slots.Count)
        {
            Slots.RemoveAllChildren();
            _roleRows.Clear();
            foreach (var slot in state.Slots)
            {
                var row = BuildRoleRow(slot);
                _roleRows.Add(row);
                Slots.AddChild(row.Root);
            }
        }

        for (var i = 0; i < state.Slots.Count && i < _roleRows.Count; i++)
        {
            var slot = state.Slots[i];
            var characterBlocked = slot.RequiresSynthetic && !state.MyCharacterIsSynthetic;
            _roleRows[i].Update(slot, i == state.MySlot, state.MySlotLocked, characterBlocked);
        }
    }

    private RoleRow BuildRoleRow(SurvivorRoleSlot slot)
    {
        var root = new Button
        {
            HorizontalExpand = true,
            StyleClasses = { "CrtButton" },
        };

        var content = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 8,
            Margin = new Thickness(4, 2),
        };
        root.AddChild(content);

        var iconTexture = RoleIcon(slot);
        var icon = new TextureRect
        {
            MinSize = new Vector2(20, 20),
            Stretch = TextureRect.StretchMode.KeepAspectCentered,
            Texture = iconTexture,
            Visible = iconTexture != null,
            VerticalAlignment = VAlignment.Center,
        };
        content.AddChild(icon);

        var text = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 0,
        };
        content.AddChild(text);

        var name = new Label { ClipText = true };
        var detail = new Label { ClipText = true, StyleClasses = { "LabelSubText" } };
        text.AddChild(name);
        text.AddChild(detail);

        var badge = new Label
        {
            MinSize = new Vector2(56, 0),
            HorizontalAlignment = HAlignment.Right,
            VerticalAlignment = VAlignment.Center,
        };
        content.AddChild(badge);

        var index = slot.Index;
        var row = new RoleRow(root, icon, name, detail, badge);
        root.OnPressed += _ =>
        {
            if (row.Claimable)
                OnClaim?.Invoke(index);
        };

        return row;
    }

    private sealed class RoleRow
    {
        public readonly Button Root;
        private readonly TextureRect _icon;
        private readonly Label _name;
        private readonly Label _detail;
        private readonly Label _badge;

        public bool Claimable { get; private set; } = true;

        public RoleRow(Button root, TextureRect icon, Label name, Label detail, Label badge)
        {
            Root = root;
            _icon = icon;
            _name = name;
            _detail = detail;
            _badge = badge;
        }

        public void Update(SurvivorRoleSlot slot, bool mine, bool locked, bool characterBlocked)
        {
            _name.Text = slot.Name;
            _icon.Modulate = Color.White;

            var raffled = slot.Contestants.Count > 0 || slot.RaffleSecondsLeft != null;

            if (mine && raffled)
            {
                var seconds = slot.RaffleSecondsLeft ?? 0;
                var names = string.Join(", ", slot.Contestants);
                _name.Text = slot.Name;
                _detail.Text = Loc.GetString("cmu-survivor-setup-slot-raffle",
                    ("contestants", names), ("seconds", seconds));
                _detail.Modulate = AccentRaffle;
                _badge.Text = Loc.GetString("cmu-survivor-setup-badge-raffle", ("seconds", seconds));
                _badge.Modulate = AccentRaffle;
                _name.Modulate = Color.White;
                Style(RaffleBg, RaffleBorder);
                Claimable = false;
                return;
            }

            if (mine)
            {
                var character = CharacterOf(slot.ClaimedBy);
                _detail.Text = character == null
                    ? Loc.GetString("cmu-survivor-setup-badge-yours")
                    : Loc.GetString("cmu-survivor-setup-slot-holder", ("character", character));
                _detail.Modulate = AccentClaimed;
                _badge.Text = Loc.GetString(locked
                    ? "cmu-survivor-setup-badge-locked"
                    : "cmu-survivor-setup-badge-yours");
                _badge.Modulate = AccentClaimed;
                _name.Modulate = AccentClaimed;
                _icon.Modulate = AccentClaimed;
                Style(ClaimedBg, AccentClaimed);
                Claimable = false;
                return;
            }

            if (slot.ClaimedBy != null)
            {
                _detail.Text = CharacterOf(slot.ClaimedBy) ?? slot.ClaimedBy;
                _detail.Modulate = Muted;
                _badge.Text = Loc.GetString("cmu-survivor-setup-badge-taken");
                _badge.Modulate = Muted;
                _name.Modulate = Muted;
                _icon.Modulate = Muted;
                Style(TakenBg, TakenBorder);
                Claimable = false;
                return;
            }

            if (characterBlocked)
            {
                // Synthetic-only role and the selected character is human: show why it cannot be taken.
                _detail.Text = Loc.GetString("cmu-survivor-setup-slot-needs-synth");
                _detail.Modulate = Muted;
                _badge.Text = Loc.GetString("cmu-survivor-setup-badge-synth");
                _badge.Modulate = Muted;
                _name.Modulate = Muted;
                Style(OpenBg, OpenBorder);
                Claimable = false;
                return;
            }

            if (slot.Contestants.Count > 0)
            {
                var names = string.Join(", ", slot.Contestants);
                var seconds = slot.RaffleSecondsLeft ?? 0;
                _name.Text = slot.Name;
                _detail.Text = Loc.GetString("cmu-survivor-setup-slot-raffle",
                    ("contestants", names), ("seconds", seconds));
                _detail.Modulate = AccentRaffle;
                _badge.Text = Loc.GetString("cmu-survivor-setup-badge-raffle", ("seconds", seconds));
                _badge.Modulate = AccentRaffle;
                _name.Modulate = Color.White;
                Style(RaffleBg, RaffleBorder);
                Claimable = !locked;
                return;
            }

            _detail.Text = string.Empty;
            _detail.Modulate = locked ? Muted : AccentOpen;
            _badge.Text = Loc.GetString("cmu-survivor-setup-badge-open");
            _badge.Modulate = locked ? Muted : AccentOpen;
            _name.Modulate = locked ? Muted : Color.White;
            Style(OpenBg, OpenBorder);
            Claimable = !locked;
        }

        private void Style(Color background, Color border)
        {
            Root.StyleBoxOverride = new StyleBoxFlat
            {
                BackgroundColor = background,
                BorderColor = border,
                BorderThickness = new Thickness(2),
                Padding = new Thickness(6, 3, 6, 3),
            };
        }

    }

    private void UpdateColumns()
    {
        var reference = Body.Size.X;
        if (reference <= 0 || Math.Abs(reference - _lastBodyWidth) < 1f)
            return;

        _lastBodyWidth = reference;
        ApplyColumnSplit();
    }

    private void ApplyColumnSplit()
    {
        if (!LoadoutSection.Visible)
        {
            Body.Orientation = BoxContainer.LayoutOrientation.Horizontal;
            LeftColumn.SizeFlagsStretchRatio = 1f;
            LeftColumn.HorizontalExpand = true;
            RightColumn.SizeFlagsStretchRatio = 1f;
            RightColumn.HorizontalExpand = false;
            return;
        }

        if (_lastBodyWidth >= TwoColumnMinimumWidth)
        {
            Body.Orientation = BoxContainer.LayoutOrientation.Horizontal;
            LeftColumn.SizeFlagsStretchRatio = 0.56f;
            LeftColumn.HorizontalExpand = true;
            RightColumn.HorizontalExpand = true;
            RightColumn.SizeFlagsStretchRatio = 0.44f;
            return;
        }

        Body.Orientation = BoxContainer.LayoutOrientation.Vertical;
        LeftColumn.SizeFlagsStretchRatio = 1f;
        RightColumn.SizeFlagsStretchRatio = 1f;
        RightColumn.HorizontalExpand = true;
    }

    private Texture? RoleIcon(SurvivorRoleSlot slot)
    {
        if (slot.IconState is { } state && slot.IconSprite is { } sprite &&
            _resourceCache.TryGetResource<RSIResource>(new ResPath(sprite), out var factionRsi) &&
