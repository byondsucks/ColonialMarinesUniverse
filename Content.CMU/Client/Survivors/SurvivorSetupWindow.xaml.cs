    private void Prime()
    {
        _voting = true;
        PhaseBadge.Text = Loc.GetString("cmu-survivor-setup-phase-vote");
        PhaseLabel.Text = Loc.GetString("cmu-survivor-setup-vote");
        TimerLabel.Text = Loc.GetString("cmu-survivor-setup-time-waiting");
        TimerLabel.Modulate = AccentGold;
        TimerBar.Value = 1f;

        VoteSection.Visible = true;
        RolesSection.Visible = false;
        CharacterSection.Visible = false;
        LoadoutSection.Visible = true;
        FactionLabel.Visible = false;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (_phaseEnd == TimeSpan.Zero)
            return;

        var remaining = _phaseEnd - _timing.CurTime;
        var seconds = Math.Max(0, (int) Math.Ceiling(remaining.TotalSeconds));

        TimerLabel.Text = Loc.GetString("cmu-survivor-setup-time-left", ("seconds", seconds));
        TimerLabel.Modulate = seconds <= 5 ? AccentRaffle : AccentGold;

        var total = Math.Max(0.001f, _phaseSeconds);
        TimerBar.Value = Math.Clamp((float) (remaining.TotalSeconds / total), 0f, 1f);
    }

    public void UpdateState(SurvivorSetupEuiState state)
    {
        _phaseEnd = state.PhaseEnd;
        _phaseSeconds = Math.Max(0.001f, state.PhaseSeconds);
        _voting = state.Phase == SurvivorSetupPhase.Vote;

        PhaseBadge.Text = Loc.GetString(_voting
            ? "cmu-survivor-setup-phase-vote"
            : "cmu-survivor-setup-phase-pick");
        PhaseLabel.Text = Loc.GetString(_voting ? "cmu-survivor-setup-vote" : "cmu-survivor-setup-pick");

        if (state.PredatorRoundFailed)
        {
            FactionLabel.Visible = true;
            FactionLabel.Text = Loc.GetString("cmu-survivor-setup-predator-failed");
            FactionLabel.Modulate = AccentRaffle;
        }
        else if (!_voting && state.ResolvedFaction != null)
        {
            FactionLabel.Visible = true;
            FactionLabel.Text = Loc.GetString("cmu-survivor-setup-faction", ("faction", state.ResolvedFaction));
            FactionLabel.Modulate = Color.White;
        }
        else
        {
            FactionLabel.Visible = false;
        }

        VoteSection.Visible = _voting;
        RolesSection.Visible = !_voting;
        CharacterSection.Visible = !_voting;
        LoadoutSection.Visible = true;

        UpdateSteps(state);

        if (_voting)
            UpdateVoteButtons(state);

        UpdateRoles(state);

        CharacterSelect.Clear();
        CharacterSelect.AddItem(Loc.GetString("cmu-survivor-setup-random"), RandomCharacterId);
        foreach (var character in state.Characters)
            CharacterSelect.AddItem(character.Name, character.Slot);

        CharacterSelect.SelectId(state.MyCharacter ?? RandomCharacterId);
        CharacterSelect.Disabled = !state.CanPickCharacter;

        UpdateLoadout(state);

        try
        {
            UpdateRoster(state);
        }
        catch (Exception e)
        {
            Logger.Error($"survivor roster panel failed: {e}");
        }

        UpdateColumns();
    }

