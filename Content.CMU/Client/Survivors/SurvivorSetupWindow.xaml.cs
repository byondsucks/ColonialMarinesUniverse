        };
        heading.AddChild(icon);

        heading.AddChild(new Label
        {
            Text = Loc.GetString(titleKey),
            StyleClasses = { "LabelKeyText" },
            VerticalAlignment = VAlignment.Center,
        });

        var select = new OptionButton { HorizontalExpand = true };
        for (var i = 0; i < options.Count; i++)
        {
            var id = options[i];
            var name = _prototypes.TryIndex<EntityPrototype>(id, out var prototype) ? prototype.Name : id;
            select.AddItem(name, i);

            if (string.Equals(id, current, StringComparison.OrdinalIgnoreCase))
                select.Select(i);
        }

        var ids = options;
        select.OnItemSelected += args =>
        {
            if (args.Id >= 0 && args.Id < ids.Count)
                OnSelectLoadout?.Invoke(category, ids[args.Id]);
        };

        LoadoutPanel.AddChild(select);

        switch (category)
        {
            case SurvivorLoadoutCategory.Armor:
                _armorSelect = select;
                _armorIcon = icon;
                break;
            case SurvivorLoadoutCategory.Helmet:
                _helmetSelect = select;
                _helmetIcon = icon;
                break;
            case SurvivorLoadoutCategory.Firearm:
                _firearmSelect = select;
                _firearmIcon = icon;
                break;
        }
    }

    /// <summary>
    ///     The group, one line per teammate. Built from the role slots, which the window already renders, so the
    ///     panel never depends on a separate roster payload arriving.
    /// </summary>
    /// <summary>
    ///     The survivor group, one card per teammate: character sprite, name, role, the loadout they picked and
    ///     whether they are done choosing. Everything comes from the server's authoritative roster.
    /// </summary>
    private void UpdateRoster(SurvivorSetupEuiState state)
    {
        var entries = ParseRoster(state);
        var signature = string.Join(Environment.NewLine, state.Roster);
        if (signature == RosterSignature && _rosterCards.Count == entries.Count)
            return;

        RosterSignature = signature;
        LastRoster = entries;
        ClearRoster();

        if (entries.Count == 0)
        {
            RosterList.AddChild(new Label
            {
                Text = Loc.GetString("cmu-survivor-setup-group-empty"),
                StyleClasses = { "LabelSubText" },
            });
            return;
        }

        foreach (var entry in entries)
            RosterList.AddChild(BuildRosterCard(entry));
    }

    /// <summary>Splits "ckey|character|role|armor|helmet|firearm|status|appearance" entries.</summary>
    private static List<RosterEntry> ParseRoster(SurvivorSetupEuiState state)
    {
        var entries = new List<RosterEntry>(state.Roster.Count);
        foreach (var raw in state.Roster)
        {
            var p = raw.Split('|');
            string Part(int i) => i < p.Length ? p[i] : string.Empty;
            entries.Add(new RosterEntry(Part(0), Part(1), Part(2), Part(3), Part(4), Part(5), Part(6), Part(7),
                Part(8), Part(9)));
        }

        return entries;
    }

    /// <summary>The character a teammate will spawn as, for the claimed role row: the roster is the only source.</summary>
    private static string? CharacterOf(string? ckey)
    {
        if (ckey == null)
            return null;

        foreach (var entry in LastRoster)
        {
            if (string.Equals(entry.Ckey, ckey, StringComparison.OrdinalIgnoreCase) && entry.Character.Length > 0)
                return entry.Character;
        }

        return null;
    }

    private Control BuildRosterCard(RosterEntry entry)
    {
        var card = new PanelContainer
        {
            HorizontalExpand = true,
            Margin = new Thickness(0, 1),
            StyleClasses = { "CrtInsetPanel" },
        };

        // A grid gives every region its own column with its own width. Labels in Robust do not wrap, so any label
        // that is allowed to exceed its box is drawn over its neighbour - which is exactly how the loadout text
        // ended up overlapping. Each column below therefore has an explicit width and clipped text.
        var grid = new GridContainer
        {
            Columns = 3,
            Margin = new Thickness(6, 3),
        };
        card.AddChild(grid);

        var preview = TryBuildPreview(entry);
        if (preview is { } sprite)
        {
            var view = new SpriteView
            {
                OverrideDirection = Direction.South,
                Scale = new Vector2(1.5f, 1.5f),
                MinSize = new Vector2(64, 64),
                MaxSize = new Vector2(64, 64),
                Stretch = SpriteView.StretchMode.None,
                VerticalAlignment = VAlignment.Center,
            };
            view.SetEntity(sprite);
            grid.AddChild(view);
        }
        else
        {
            grid.AddChild(new Control { MinSize = new Vector2(64, 64) });
        }

        var identity = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            MinSize = new Vector2(140, 0),
            SeparationOverride = 1,
            VerticalAlignment = VAlignment.Center,
        };
        grid.AddChild(identity);

        identity.AddChild(new Label
        {
            Text = entry.Character.Length > 0 ? entry.Character : entry.Ckey,
            HorizontalExpand = true,
            ClipText = true,
        });

        var roleText = entry.Role.Length > 0 ? entry.Role : Loc.GetString("cmu-survivor-setup-roster-no-role");
        identity.AddChild(new Label
        {
            // A named character's role name is their own name (Dutch), so don't print it twice.
            Text = string.Equals(roleText, entry.Character, StringComparison.OrdinalIgnoreCase)
                ? Loc.GetString("cmu-survivor-setup-roster-role-only", ("role", entry.Role))
                : roleText,
            HorizontalExpand = true,
            ClipText = true,
            StyleClasses = { "LabelSubText" },
        });

        identity.AddChild(new Label
        {
            Text = Loc.GetString(entry.Status switch
            {
                "ready" => "cmu-survivor-setup-roster-ready",
                "choosing" => "cmu-survivor-setup-roster-choosing",
                _ => "cmu-survivor-setup-roster-waiting",
            }),
            StyleClasses = { "LabelSubText" },
            Modulate = entry.Status == "ready" ? AccentOpen : Muted,
            // Wide enough for the longest status and clipped besides: an unclipped label that overflows its
            // column is drawn over the loadout text beside it, which is what cut "M10 pattern marine helmet" off
            // at "heln" with "Ready" sitting on top of it.
            ClipText = true,
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Center,
        });

        // Loadout: three stacked categories, each its own box so no row can be squeezed into another.
        // Bounded on both sides: ClipText truncates against the parent's width, so a column free to grow lets its
        // labels draw past it and over the status text beside it.
        var loadout = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            // Wide enough for every name the factions actually issue ("M10 pattern marine helmet" is the longest),
            // and fixed so the labels clip inside it rather than spilling out of the card.
            MinSize = new Vector2(300, 0),
            MaxSize = new Vector2(300, float.MaxValue),
            SeparationOverride = 2,
            VerticalAlignment = VAlignment.Center,
        };
        grid.AddChild(loadout);

        if (entry.LoadoutState == "selected")
        {
            AddLoadoutRow(loadout, "cmu-survivor-setup-roster-armor", entry.Armor);
            AddLoadoutRow(loadout, "cmu-survivor-setup-roster-helmet", entry.Helmet);
            AddLoadoutRow(loadout, "cmu-survivor-setup-roster-gun", entry.Firearm);
        }
        else
        {
            // Nothing chosen yet: say so instead of showing the faction's default kit as if it were picked.
            loadout.AddChild(new Label
            {
                Text = Loc.GetString(entry.LoadoutState == "pending"
                    ? "cmu-survivor-setup-roster-loadout-pending"
                    : "cmu-survivor-setup-roster-loadout-none"),
                StyleClasses = { "LabelSubText" },
                Modulate = Muted,
                ClipText = true,
                HorizontalExpand = true,
            });
        }

        return card;
    }

    /// <summary>One loadout category: a dim heading above the selected item's name.</summary>
    private void AddLoadoutRow(BoxContainer column, string headingKey, string protoId)
    {
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 0,
        };
        column.AddChild(row);

        row.AddChild(new Label
        {
            Text = Loc.GetString(headingKey),
            StyleClasses = { "LabelSubText" },
            Modulate = Muted,
            ClipText = true,
            HorizontalExpand = true,
        });

        row.AddChild(new Label
        {
            Text = protoId.Length > 0 ? ItemName(protoId) : Loc.GetString("cmu-survivor-setup-roster-none"),
            ClipText = true,
            HorizontalExpand = true,
        });
    }

    /// <summary>The item's own display name, so the card never shows a prototype id.</summary>
    private string ItemName(string protoId)
        => _prototypes.TryIndex<EntityPrototype>(protoId, out var prototype) ? prototype.Name : protoId;

    /// <summary>Body-id prefixes stripped when building a survivor role's job id.</summary>
    private static readonly string[] SurvivorJobPrefixes =
    {
        "CMUSurvivor", "CMUSurv", "CMU14Job", "CMUJob", "AU14Job", "AU14", "CMU",
    };

    private EntityUid? TryBuildPreview(RosterEntry entry)
    {
        if (entry.Appearance.Length == 0)
            return null;

        try
        {
            var bytes = Convert.FromBase64String(entry.Appearance);
            using var stream = new MemoryStream(bytes);
            var profile = IoCManager.Resolve<IRobustSerializer>().Deserialize<HumanoidCharacterProfile>(stream);

            // Dress the preview in the role's job gear so the card shows the uniform, armour and helmet that role
            // spawns in. A bare role body would come out naked: its equipment is applied by a server-only preset.
            // The roster carries the role *body* id, so the job has to be read from that body's ghost role - indexing
            // the body id as a job silently failed and left every card naked.
            var job = JobOfRole(entry.RoleProto);

            var preview = _ui.GetUIController<LobbyUIController>()
                .LoadProfileEntity(profile, job, job != null);

            if (!preview.Valid)
                return null;

            _rosterDummies.Add(preview);
            return preview;
        }
        catch (Exception e)
        {
            Logger.Error($"survivor roster preview for {entry.Ckey} failed: {e}");
            return null;
        }
    }

    private void ClearRoster()
    {
        RosterList.RemoveAllChildren();
        foreach (var dummy in _rosterDummies)
        {
            if (!_entManager.Deleted(dummy))
                _entManager.DeleteEntity(dummy);
        }

        _rosterDummies.Clear();
        _rosterCards.Clear();
    }

